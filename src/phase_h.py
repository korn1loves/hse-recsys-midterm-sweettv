"""Phase H driver: learned re-ranker (HistGradientBoostingClassifier) over component candidates.

Training/evaluation without leakage:
- main (target 21-30): model trained on W0 (11-15 -> 16-20) only;
- secondary (target 25-30): trained on W0 + W1b (11-20 -> 21-24);
- final (TEST 11-30 -> 31-42): trained on W0 + W1 (11-20 -> 21-30) + W2 (11-24 -> 25-30);
- h03: final model trained on W1 + W2 only.
Writes results/phaseH.md, results/phaseH_grid.csv, results/phaseH_importance.csv,
results/phaseH_manifest.csv, results/submission_h01..h03.csv.
"""
import itertools
import time

import numpy as np
import pandas as pd
from sklearn.ensemble import HistGradientBoostingClassifier

import data
import join
import phase_d as PD
import scoring as SC
from cbf import item_table
from metrics import mapk
from rerank import CAT_IDX, FEATURES, blend, build, preds_from_scores

RES = data.ROOT / "results"
WINDOWS = {"W0": (range(11, 16), range(16, 21)), "W1": (range(11, 21), range(21, 31)),
           "W2": (range(11, 25), range(25, 31)), "W1b": (range(11, 21), range(21, 25)),
           "TEST": (range(11, 31), range(31, 43))}
GRID = list(itertools.product([0.05, 0.1], [15, 31], [200, 400]))


def fit(ws, cfg):
    lr, leaves, iters = cfg
    X = np.vstack([w["X"][w["train_mask"]] for w in ws])
    y = np.concatenate([w["y"][w["train_mask"]] for w in ws])
    cat = np.zeros(X.shape[1], dtype=bool)
    cat[CAT_IDX] = True
    X = X.copy()
    X[:, CAT_IDX] = X[:, CAT_IDX] + 1  # -1 (unknown) -> 0; HGB categories must be non-negative
    m = HistGradientBoostingClassifier(learning_rate=lr, max_leaf_nodes=leaves, max_iter=iters,
                                       early_stopping=True, validation_fraction=0.1, n_iter_no_change=20,
                                       categorical_features=cat, random_state=0)
    t = time.time()
    m.fit(X, y)
    m.fit_s = time.time() - t
    return m


def score(m, w, X=None):
    X = (w["X"] if X is None else X).copy()
    X[:, CAT_IDX] = X[:, CAT_IDX] + 1
    return m.predict_proba(X)[:, 1]


def ap_vec(w, preds):
    return SC.ap_per_user(w["sp"].target, preds)[1]


def main():
    T0 = time.time()
    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    it = item_table(("11-20", "21-30", "31-42"))
    cats = pd.Series(pd.Categorical(it.tv_show_category.fillna("?")).codes, index=it.index)
    W, build_s = {}, {}
    for k, (hw, tw) in WINDOWS.items():
        t = time.time()
        W[k] = build(k, itx, hw, tw, users, cats)
        build_s[k] = time.time() - t
        print(k, "recall", W[k]["recall"], "avg cand", W[k]["avg_cand"], f"{build_s[k]:.1f}s")
    md = ["## 14. Phase H: learned re-ranker (generated by src/phase_h.py)\n",
          "Candidate generation (union of top-30 per component + top-30 pool popularity; submission users only):\n",
          pd.DataFrame([{"window": k, "history": f"{min(h)}-{max(h)}", "target": f"{min(t)}-{max(t)}",
                         "avg candidates/user": round(W[k]["avg_cand"], 1),
                         "candidate recall": "n/a (no target)" if k == "TEST" else round(W[k]["recall"], 4),
                         "positives": int(W[k]["y"].sum()), "rows": len(W[k]["y"]), "build_s": round(build_s[k], 1)}
                        for k, (h, t) in WINDOWS.items()]).to_markdown(index=False), ""]

    ev = {"main": (["W0"], W["W1"]), "secondary": (["W0", "W1b"], W["W2"])}
    ap_f03 = {s: ap_vec(w, SC.topk(*w["f03"], w["sp"], w["fb"])) for s, (_, w) in ev.items()}

    rows, models = [], {}
    for cfg in GRID:
        r = {"learning_rate": cfg[0], "max_leaf_nodes": cfg[1], "max_iter": cfg[2]}
        for s, (tr, w) in ev.items():
            m = fit([W[k] for k in tr], cfg)
            p, _, _ = preds_from_scores(w, score(m, w))
            r[s] = ap_vec(w, p).mean()
            r[f"iters_{s}"] = m.n_iter_
            r[f"fit_s_{s}"] = round(m.fit_s, 1)
            models[(cfg, s)] = m
        r["mean"] = (r["main"] + r["secondary"]) / 2
        rows.append(r)
        print(r)
    g = pd.DataFrame(rows).sort_values("mean", ascending=False)
    g.to_csv(RES / "phaseH_grid.csv", index=False)
    best = tuple(g.iloc[0][["learning_rate", "max_leaf_nodes", "max_iter"]])
    best = (float(best[0]), int(best[1]), int(best[2]))

    # comparison vs f03 with paired bootstrap; blend
    comp, pred_times = [], {}
    for s, (tr, w) in ev.items():
        m = models[(best, s)]
        t = time.time()
        p, S, V = preds_from_scores(w, score(m, w))
        pred_s = time.time() - t
        pb = blend(w, S, V)
        for name, pr in [("Re-ranker (best grid)", p), ("Blend: rank-avg re-ranker/f03 0.5/0.5", pb)]:
            a = ap_vec(w, pr)
            d = a - ap_f03[s]
            lo, hi = SC.bootstrap_ci(d)
            comp.append({"split": s, "method": name, "MAP@5": a.mean(),
                         "Δ vs f03 [95% CI]": f"{d.mean():+.5f} [{lo:+.5f}, {hi:+.5f}]"})
        comp.append({"split": s, "method": "f03", "MAP@5": ap_f03[s].mean(), "Δ vs f03 [95% CI]": "—"})
        if s == "secondary":  # analogue of h03 (longer-history window only): trained on W1b alone
            m3 = fit([W["W1b"]], best)
            p3, _, _ = preds_from_scores(w, score(m3, w))
            a = ap_vec(w, p3)
            d = a - ap_f03[s]
            lo, hi = SC.bootstrap_ci(d)
            comp.append({"split": s, "method": "Re-ranker trained on W1b only (h03 analogue)", "MAP@5": a.mean(),
                         "Δ vs f03 [95% CI]": f"{d.mean():+.5f} [{lo:+.5f}, {hi:+.5f}]"})
        pred_times[s] = pred_s
    comp = pd.DataFrame(comp)

    # permutation importance on main (MAP@5 drop, 3 repeats, seed 0)
    w, m = W["W1"], models[(best, "main")]
    base = ap_vec(w, preds_from_scores(w, score(m, w))[0]).mean()
    rng = np.random.default_rng(0)
    imp = []
    for j, f in enumerate(FEATURES):
        drops = []
        for _ in range(3):
            X = w["X"].copy()
            X[:, j] = X[rng.permutation(len(X)), j]
            drops.append(base - ap_vec(w, preds_from_scores(w, score(m, w, X))[0]).mean())
        imp.append({"feature": f, "MAP@5 drop": np.mean(drops), "std": np.std(drops)})
    imp = pd.DataFrame(imp).sort_values("MAP@5 drop", ascending=False)
    imp.to_csv(RES / "phaseH_importance.csv", index=False)

    # final models and files
    t = time.time()
    wt = W["TEST"]
    m_all = fit([W["W0"], W["W1"], W["W2"]], best)
    p1, S1, V1 = preds_from_scores(wt, score(m_all, wt))
    p2 = blend(wt, S1, V1)
    m_long = fit([W["W1"], W["W2"]], best)
    p3, _, _ = preds_from_scores(wt, score(m_long, wt))
    pool = np.asarray(wt["sp"].pool)
    vals = lambda name: [comp[(comp.split == s) & (comp.method == name)]["MAP@5"].iloc[0] for s in ("main", "secondary")]
    man = []
    for fn, p, desc, trained, vname in [
            ("submission_h01.csv", p1, "re-ranker (best grid)", "W0+W1+W2", "Re-ranker (best grid)"),
            ("submission_h02.csv", p2, "rank-average blend re-ranker/f03 0.5/0.5", "W0+W1+W2", "Blend: rank-avg re-ranker/f03 0.5/0.5"),
            ("submission_h03.csv", p3, "re-ranker, longer-history windows only", "W1+W2", None)]:
        PD.write_sub(p, pool, fn)
        x = pd.read_csv(RES / fn, dtype=str).tv_show_id.str.split()
        y = pd.read_csv(RES / "submission_f03.csv", dtype=str).tv_show_id.str.split()
        ov = sum(len(set(a) & set(b)) for a, b in zip(x, y)) / (5 * len(x))
        mv = vals(vname) if vname else [np.nan, comp[comp.method.str.contains("W1b only")]["MAP@5"].iloc[0]]
        man.append({"file": f"results/{fn}", "method": desc, "trained_on": trained,
                    "params": f"lr={best[0]} leaves={best[1]} max_iter={best[2]} (early stopping)",
                    "main": round(mv[0], 5) if mv[0] == mv[0] else "n/a", "secondary": round(mv[1], 5),
                    "overlap_with_f03": round(ov, 3)})
    man = pd.DataFrame(man)
    man.to_csv(RES / "phaseH_manifest.csv", index=False)

    md += [f"Model: HistGradientBoostingClassifier (seed 0, early stopping on 10% internal validation, "
           f"n_iter_no_change 20, category as a categorical feature). {len(FEATURES)} features: "
           f"{', '.join(FEATURES)}. Training rows: users with a non-empty target in that window.\n",
           "Grid (main: trained on W0; secondary: trained on W0+W1b; ranked by mean):\n",
           g.to_markdown(index=False, floatfmt=".5f"), "",
           f"Best: learning_rate={best[0]}, max_leaf_nodes={best[1]}, max_iter={best[2]}.\n",
           "Comparison (paired bootstrap vs f03, 1000 resamples, seed 0):\n",
           comp.to_markdown(index=False, floatfmt=".5f"), "",
           "Re-ranker predict time (score candidates + top-5): "
           + ", ".join(f"{k} {v:.2f}s" for k, v in pred_times.items()) + "\n",
           "Permutation importance on main (MAP@5 drop when the feature is shuffled across candidate rows; "
           "3 repeats, seed 0), top 15:\n", imp.head(15).to_markdown(index=False, floatfmt=".5f"), "",
           f"Final models: W0+W1+W2 ({m_all.n_iter_} iterations, fit {m_all.fit_s:.1f}s); W1+W2 "
           f"({m_long.n_iter_} iterations, fit {m_long.fit_s:.1f}s). Files (validated; {time.time() - t:.1f}s):\n",
           man.to_markdown(index=False), "",
           "h03 has no leak-free main-split analogue (no earlier long-history window exists); its secondary "
           "number is for a model trained on W1b (11-20 -> 21-24) only.\n",
           f"Phase H runtime {time.time() - T0:.1f}s\n"]
    (RES / "phaseH.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
