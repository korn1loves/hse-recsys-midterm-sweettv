"""Phase M: re-target to episode-equivalents (T5) everywhere.

1. Target-variant probe (personal-history rankings x target variants a-d) + files l06-l08.
2. Components in episode units (phase_e.EPISODES): personal episodes, episode rate, habit exposure in
   expected episodes (per-airing item side), AR on >= 0.5-episode sets, MF with confidence log1p(episodes),
   popularity / fallback in episodes.
3. Hand hybrid (min-max fusion) re-tuned on MAIN under T5, reported on SECONDARY; re-ranker v2 retrained
   with T5 graded labels on episode features (Phase J windows and leak rule); 0.5/0.5 rank-average of both.
Writes results/phaseM.md, results/phaseM_probe.csv, results/phaseM_hybrid_grid.csv,
results/phaseM_manifest.csv, results/submission_l06..l08.csv, results/submission_m01..m03(+m04).csv.
"""
import itertools
import time

import numpy as np
import pandas as pd

import baselines as B
import data
import episodes as E
import join
import phase_d as PD
import phase_e as PE
import rerank as R
import scoring as SC
from cbf import item_table
from metrics import mapk
from phase_j import NEW_COMPS, NEWF, WINDOWS, allowed, fit, scores
from phase_k import rank_blend

RES = data.ROOT / "results"
PE.EPISODES = True
PE.HABITS = ["slot_4", "daypart_4", "channel_4", "daypart_None"]
VP = ("11-20", "21-30")
TV = {"a": "a: watched (>= 300 s)", "b": "b: all airings", "c": "c: fraction >= 0.25", "d": "d: overlap >= 60 s"}
RV = {"all": "l05: all airings", "w300": "l06: watched >= 300 s", "f25": "l07: fraction >= 0.25",
      "hl8": "l08: all airings, half-life 8"}
HGRID = dict(rate=[0, 0.25, 0.5, 1], ar=[0, 0.25], mf=[0, 0.5, 1], daypart_4=[0, 0.5, 1], channel_4=[0, 0.5])
RGRID = [(0.05, 15, 200), (0.05, 31, 200), (0.1, 15, 200), (0.1, 31, 200)]


def boot(a, b):
    d = a - b
    lo, hi = SC.bootstrap_ci(d)
    return f"{d.mean():+.5f} [{lo:+.5f}, {hi:+.5f}]"


def main():
    T0 = time.time()
    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    md = ["## 19. Phase M: episode-equivalent target everywhere (generated by src/phase_m.py)\n"]

    # ---------------- 1. probe
    probe, l05_ref, sp_sec = [], {}, {}
    for split, (hw, tw) in B.SPLITS.items():
        sp_sec[split] = B.make_split(split, itx, 0, users)
        fb = B.popularity(sp_sec[split])  # seconds fallback, exactly as in submission_l05.csv
        tg = {t: E.target_ep(itx, tw, users, t) for t in TV}
        for rv, rname in RV.items():
            p = E.rank_personal(itx, hw, sp_sec[split].pool, users, rv, fb)
            if rv == "all":
                l05_ref[split] = p
            probe.append({"split": split, "history ranking": rname, **{TV[t]: mapk(tg[t], p) for t in TV}})
    probe = pd.DataFrame(probe)
    probe.to_csv(RES / "phaseM_probe.csv", index=False)
    hist = join.user_show_week(join.watched(itx, min_sec=0))
    hist = hist[hist.week.between(11, 30)]
    pool_t = B.pool_from_schedule(("31-42",), range(31, 43))
    fb_t = B.popularity(B.Split("final", hist, pool_t, users, {}, 30))
    lman = []
    for fn, rv in [("submission_l05_check.csv", "all"), ("submission_l06.csv", "w300"),
                   ("submission_l07.csv", "f25"), ("submission_l08.csv", "hl8")]:
        p = E.rank_personal(itx, range(11, 31), pool_t, users, rv, fb_t)
        B.check_preds(p, users, pool_t)
        PD.write_sub(p, pool_t, fn)
    l05_same = (RES / "submission_l05_check.csv").read_bytes() == (RES / "submission_l05.csv").read_bytes()
    (RES / "submission_l05_check.csv").unlink()
    md += ["### Target-variant probe (personal-history rankings; seconds fallback as in the l05 file)\n"]
    for split in B.SPLITS:
        md += [f"**{split}**\n", probe[probe.split == split].drop(columns="split").to_markdown(index=False, floatfmt=".5f"), ""]
    md += [f"Check: the l05 rule recomputed here reproduces `submission_l05.csv` byte-for-byte: **{l05_same}**.\n"]

    # ---------------- 2./3. episode components, hand hybrid
    sps, comps, fbs = {}, {}, {}
    for split, (hw, tw) in B.SPLITS.items():
        h = E.ep_hist(itx)
        sp = B.Split(split, h[h.week.isin(list(hw))], sp_sec[split].pool, users, E.target_ep(itx, tw, users), max(hw))
        sps[split], fbs[split] = sp, B.popularity(sp)
        comps[split], _ = PE.components(sp, list(hw), list(tw), VP, VP)
        print(split, "components", f"{time.time() - T0:.0f}s")
    ref = {s: SC.ap_per_user(sps[s].target, l05_ref[s])[1] for s in B.SPLITS}

    def ev(s, w):
        return SC.ap_per_user(sps[s].target, SC.topk(*PE.fuse(comps[s], w), sps[s], fbs[s]))[1]

    single = []
    for k in ["pers", "rate", "ar", "mf", "slot_4", "daypart_4", "channel_4", "daypart_None"]:
        r = {"component (episode units)": k}
        for s in B.SPLITS:
            r[s] = ev(s, {k: 1.0}).mean()
        single.append(r)
    single = pd.DataFrame(single)
    hrows = []
    for vals in itertools.product(*HGRID.values()):
        w = {"pers": 1.0, **dict(zip(HGRID, vals))}
        hrows.append({**{f"w_{k}": v for k, v in w.items()}, "MAP@5_main": ev("main", w).mean(), "_w": w})
    hg = pd.DataFrame(hrows).sort_values("MAP@5_main", ascending=False).reset_index(drop=True)
    WH = hg.iloc[0]["_w"]
    hg.drop(columns="_w").to_csv(RES / "phaseM_hybrid_grid.csv", index=False)
    print("hybrid", WH, f"{time.time() - T0:.0f}s")

    # ---------------- re-ranker v2 on T5 / episode features
    R.HIST_FN = lambda x: E.ep_hist(x)
    R.TARGET_FN = lambda x, tw, us: E.target_ep(x, tw, us)
    it = item_table(("11-20", "21-30", "31-42"))
    cats = pd.Series(pd.Categorical(it.tv_show_category.fillna("?")).codes, index=it.index)
    W = {k: R.build(k, itx, hw, tw, users, cats, fusions={"hyb": WH}, topn=50, cand_comps=NEW_COMPS, extra=True)
         for k, (hw, tw) in WINDOWS.items()}
    print("windows", f"{time.time() - T0:.0f}s")
    used = {s: allowed(s) for s in ("main", "secondary", "test")}
    tw_of = {"main": "W1", "secondary": "W2", "test": "TEST"}
    rr_rows, rr_S = [], {}
    for cfg in RGRID:
        r = {"learning_rate": cfg[0], "max_leaf_nodes": cfg[1], "max_iter": cfg[2]}
        for s in ("main", "secondary"):
            m = fit([W[k] for k in used[s]], cfg, NEWF, True)
            w = W[tw_of[s]]
            p, S, V = R.preds_from_scores(w, scores(m, w))
            r[s] = SC.ap_per_user(w["sp"].target, p)[1].mean()
            rr_S[(cfg, s)] = (S, V)
        r["mean"] = (r["main"] + r["secondary"]) / 2
        rr_rows.append(r)
    rg = pd.DataFrame(rr_rows).sort_values("mean", ascending=False)
    best = tuple(rg.iloc[0][["learning_rate", "max_leaf_nodes", "max_iter"]])
    best = (float(best[0]), int(best[1]), int(best[2]))

    # ---------------- comparison
    comp = []
    for s in ("main", "secondary"):
        w = W[tw_of[s]]
        assert w["sp"].target == sps[s].target
        Sh, Vh = w["fus"]["hyb"]
        Sr, Vr = rr_S[(best, s)]
        meths = {"l05 (personal episodes, Kaggle 0.39335)": l05_ref[s],
                 "personal episodes (episode fallback)": SC.topk(*comps[s]["pers"], sps[s], fbs[s]),
                 "hand hybrid, episodes (m01)": SC.topk(Sh, Vh, w["sp"], w["fb"]),
                 "re-ranker v2, T5 (m02)": SC.topk(Sr, Vr, w["sp"], w["fb"]),
                 "m01 + m02 rank-average 0.5/0.5 (m03)": rank_blend(w, [(Sh, Vh, 0.5), (Sr, Vr, 0.5)])}
        for name, p in meths.items():
            a = SC.ap_per_user(w["sp"].target, p)[1]
            comp.append({"split": s, "method": name, "MAP@5": a.mean(),
                         "Δ vs l05": "—" if name.startswith("l05") else boot(a, ref[s])})
    comp = pd.DataFrame(comp)
    wide = comp.pivot(index="method", columns="split", values="MAP@5")
    wide["mean"] = wide.mean(axis=1)
    for s in ("main", "secondary"):
        wide[f"Δ {s} vs l05"] = comp[comp.split == s].set_index("method")["Δ vs l05"]
    wide = wide.sort_values("mean", ascending=False)

    # ---------------- TEST files
    t = time.time()
    wt = W["TEST"]
    pool = np.asarray(wt["sp"].pool)
    m_rr = fit([W[k] for k in used["test"]], best, NEWF, True)
    _, Sr, Vr = R.preds_from_scores(wt, scores(m_rr, wt))
    Sh, Vh = wt["fus"]["hyb"]
    files = {"submission_m01.csv": ("hand hybrid, episodes (m01)", SC.topk(Sh, Vh, wt["sp"], wt["fb"])),
             "submission_m02.csv": ("re-ranker v2, T5 (m02)", SC.topk(Sr, Vr, wt["sp"], wt["fb"])),
             "submission_m03.csv": ("m01 + m02 rank-average 0.5/0.5 (m03)", rank_blend(wt, [(Sh, Vh, 0.5), (Sr, Vr, 0.5)]))}
    top = wide.index[0]
    note = (f"- m04 not written: the best method by mean on validation (`{top}`) is already one of m01-m03 or the "
            "Phase L l05 file." if top in [v[0] for v in files.values()] or top.startswith("l05") else "")
    l05f = pd.read_csv(RES / "submission_l05.csv", dtype=str).tv_show_id.str.split()
    man = []
    for fn, (meth, p) in files.items():
        B.check_preds(p, users, pool)
        PD.write_sub(p, pool, fn)
        x = pd.read_csv(RES / fn, dtype=str).tv_show_id.str.split()
        man.append({"file": f"results/{fn}", "method": meth,
                    "details": (" ".join(f"{k}={v:g}" for k, v in WH.items() if v) if "hybrid" in meth or "m03" in meth else "")
                    + (f" | re-ranker lr={best[0]} leaves={best[1]} on {'+'.join(used['test'])}" if "m01" not in meth or "m03" in meth else ""),
                    "main": round(wide.loc[meth, "main"], 5), "secondary": round(wide.loc[meth, "secondary"], 5),
                    "mean": round(wide.loc[meth, "mean"], 5),
                    "overlap_with_l05": round(sum(len(set(a) & set(b)) for a, b in zip(x, l05f)) / (5 * len(x)), 3)})
    for i, rv in [(6, "w300"), (7, "f25"), (8, "hl8")]:
        x = pd.read_csv(RES / f"submission_l0{i}.csv", dtype=str).tv_show_id.str.split()
        pr = probe[probe.history_ranking == RV[rv]] if "history_ranking" in probe else probe[probe["history ranking"] == RV[rv]]
        man.append({"file": f"results/submission_l0{i}.csv", "method": f"personal history, {RV[rv]}", "details": "seconds fallback (as l05)",
                    "main": round(pr[pr.split == "main"][TV["a"]].iloc[0], 5),
                    "secondary": round(pr[pr.split == "secondary"][TV["a"]].iloc[0], 5),
                    "mean": round(pr[TV["a"]].mean(), 5),
                    "overlap_with_l05": round(sum(len(set(a) & set(b)) for a, b in zip(x, l05f)) / (5 * len(x)), 3)})
    man = pd.DataFrame(man)
    man.to_csv(RES / "phaseM_manifest.csv", index=False)

    md += ["### Episode-unit components alone (target T5a; episode-popularity fallback)\n",
           single.to_markdown(index=False, floatfmt=".5f"), "",
           f"### Hand hybrid grid on MAIN ({len(hg)} configs, pers fixed at 1), top 10\n",
           hg.drop(columns="_w").head(10).to_markdown(index=False, floatfmt=".5f"), "",
           f"Chosen hand-hybrid weights: {WH}\n",
           "### Re-ranker v2 on T5 (graded labels 5..1; episode features; windows used: "
           + "; ".join(f"{s}: {'+'.join(v)}" for s, v in used.items()) + ")\n",
           rg.to_markdown(index=False, floatfmt=".5f"), "",
           "### Comparison under T5 (paired bootstrap vs l05, 1000 resamples, seed 0)\n",
           wide.to_markdown(floatfmt=".5f"), "",
           f"### Files (validated; TEST refit {time.time() - t:.1f}s)\n", man.to_markdown(index=False), "", note, "",
           f"Phase M runtime {time.time() - T0:.1f}s\n"]
    (RES / "phaseM.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
