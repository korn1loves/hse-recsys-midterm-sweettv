"""Phase D2: small grid around Hybrid3 on BOTH splits, ranked by mean(main, secondary) MAP@5.
Writes results/phaseD2.md, results/phaseD2_grid.csv, results/submission_hybrid4.csv
(+ submission_hybrid5.csv = best with w_exp <= 1, if different)."""
import itertools
import time

import numpy as np
import pandas as pd

import baselines as B
import data
import join
import phase_d as PD
import scoring as SC
from hybrid import fuse
from metrics import mapk

RES = data.ROOT / "results"
PD.HLS = [None, 4, 8]
H3 = {"pers": 1.0, "rate": 0.5, "exp_4": 2.0, "ar": 0.25, "mf": 1.0}
GRID = dict(w_exp=[0.5, 1, 2, 3, 4], hl=[None, 4, 8], w_rate=[0.25, 0.5, 1], w_pers=[1, 2])


def hl_key(hl):
    return None if hl is None or (isinstance(hl, float) and np.isnan(hl)) else int(hl)


def weights(r):
    return {"pers": float(r["w_pers"]), "rate": float(r["w_rate"]), f"exp_{hl_key(r['hl'])}": float(r["w_exp"]),
            "ar": 0.25, "mf": 1.0}


def main():
    T0 = time.time()
    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    VP = ("11-20", "21-30")
    sp, comps, fb = {}, {}, {}
    for s, (hw, tw) in B.SPLITS.items():
        sp[s] = B.make_split(s, itx, 0, users)
        fb[s] = B.popularity(sp[s])
        comps[s], _ = PD.comps_for(sp[s], list(hw), list(tw), VP, VP)

    def preds(s, w):
        return SC.topk(*fuse(comps[s], w), sp[s], fb[s])

    rows = []
    for we, hl, wr, wp in itertools.product(*GRID.values()):
        r = {"w_pers": wp, "w_rate": wr, "w_exp": we, "hl": hl, "w_ar": 0.25, "w_mf": 1.0}
        for s in sp:
            r[f"MAP@5_{s}"] = mapk(sp[s].target, preds(s, weights(r)))
        r["mean"] = (r["MAP@5_main"] + r["MAP@5_secondary"]) / 2
        rows.append(r)
    g = pd.DataFrame(rows).sort_values("mean", ascending=False).reset_index(drop=True)
    g["hl"] = g["hl"].astype(object).where(g["hl"].notna(), None)
    g.to_csv(RES / "phaseD2_grid.csv", index=False)

    # paired bootstrap vs Hybrid3 for the top 10
    ap_h3 = {s: SC.ap_per_user(sp[s].target, preds(s, H3))[1] for s in sp}
    top = g.head(10).copy()
    for s in sp:
        cis = []
        for _, r in top.iterrows():
            d = SC.ap_per_user(sp[s].target, preds(s, weights(r)))[1] - ap_h3[s]
            lo, hi = SC.bootstrap_ci(d)
            cis.append(f"{d.mean():+.5f} [{lo:+.5f}, {hi:+.5f}]")
        top[f"Δ vs H3 {s}"] = cis
    h3_main, h3_sec = ap_h3["main"].mean(), ap_h3["secondary"].mean()

    best = g.iloc[0]
    cons = g[g.w_exp <= 1].iloc[0]
    W4, W5 = weights(best), weights(cons)
    finals = {"submission_hybrid4.csv": W4}
    if W5 != W4:
        finals["submission_hybrid5.csv"] = W5

    # refit on weeks 11-30, pool from 31-42
    hist = join.user_show_week(join.watched(itx, min_sec=0))
    hist = hist[hist.week.between(11, 30)]
    pool = B.pool_from_schedule(("31-42",), range(31, 43))
    spf = B.Split("final", hist, pool, users, {}, 30)
    cf, _ = PD.comps_for(spf, list(range(11, 31)), list(range(31, 43)), VP, ("31-42",))
    fbf = B.popularity(spf)
    for fn, w in finals.items():
        p = SC.topk(*fuse(cf, w), spf, fbf)
        B.check_preds(p, users, pool)
        PD.write_sub(p, pool, fn)

    md = ["### Phase D2: grid around Hybrid3 on both splits (generated by src/phase_d2.py)\n",
          f"Grid: {GRID} with AR 0.25 and MF 1 fixed; {len(g)} configs. Selection rule: rank by the mean of "
          "main and secondary MAP@5 (secondary is closer to the test horizon). Kaggle scores were NOT used "
          "for tuning.\n",
          f"Hybrid3 reference: main {h3_main:.5f}, secondary {h3_sec:.5f}, mean {(h3_main + h3_sec) / 2:.5f}.\n",
          "Top 10 (Δ = paired bootstrap mean difference vs Hybrid3, 95% CI, 1000 resamples, seed 0):\n",
          top.to_markdown(index=False, floatfmt=".5f"), "",
          f"- **Hybrid4** (best by mean): {W4} → main {best['MAP@5_main']:.5f}, secondary "
          f"{best['MAP@5_secondary']:.5f}, mean {best['mean']:.5f} → `results/submission_hybrid4.csv`",
          f"- **Hybrid5** (best with w_exp ≤ 1, conservative): {W5} → main {cons['MAP@5_main']:.5f}, secondary "
          f"{cons['MAP@5_secondary']:.5f}, mean {cons['mean']:.5f}"
          + (" → `results/submission_hybrid5.csv`" if "submission_hybrid5.csv" in finals else " (same as Hybrid4, not written)"),
          f"- Refit on weeks 11-30 with the 31-42 schedule pool ({len(pool):,} shows); files validated with the "
          "Phase A checks.",
          f"\nPhase D2 runtime {time.time() - T0:.1f}s\n"]
    (RES / "phaseD2.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
