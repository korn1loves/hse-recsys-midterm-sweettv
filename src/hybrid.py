"""Phase B/C driver: MF grid, CBF, AR, hybrid fusion, comparison with bootstrap CIs, example users,
final submission. Writes results/phaseBC.md, results/mf_grid.csv, results/hybrid_grid.csv,
results/comparison.csv, results/examples.md, results/submission_final.csv.

Hybrid = weighted score fusion after per-user min-max over the pool:
  score = w_pers * mm(personal seconds) + w_mf * mm(MF) + w_cbf * mm(CBF) + w_ar * mm(AR);
valid items = union of the valid sets of components with w > 0; top-5 + Phase A fallback.
Weights chosen on MAIN, reported on SECONDARY.
"""
import itertools
import json
import time

import numpy as np
import pandas as pd

import baselines as B
import data
import join
import scoring as SC
from ar import MIN_CONF, MIN_SUPPORT, SET_MIN_SEC, ar_scores
from cbf import cbf_scores, item_table
from make_submission import validate
from metrics import apk, mapk
from mf import mf_scores

RES = data.ROOT / "results"
HIST_MIN_SEC = 0  # Phase A choice for history
MF_GRID = list(itertools.product([32, 64], [0.1, 1.0], [1.0, 10.0]))
W_MF = [0, 0.05, 0.1, 0.25, 0.5, 1.0]
W_CBF = [0, 0.05, 0.1, 0.25]
W_AR = [0, 0.05, 0.1, 0.25, 0.5]
VAL_PARTS = ("11-20", "21-30")


def fuse(comps, w):
    """comps: name -> (S, valid). Returns fused (S, valid)."""
    S, V = None, None
    for name, wt in w.items():
        if wt == 0:
            continue
        s, v = comps[name]
        z = wt * SC.minmax_rows(s, v)
        S = z if S is None else S + z
        V = v.copy() if V is None else (V | v)
    return S, V


def components(sp, mf_cfg, parts):
    comps, rt = {}, {}
    t = time.time()
    comps["pers"] = SC.personal_scores(sp)
    rt["personal"] = {"fit_s": time.time() - t, "predict_s": 0.0}
    S, v, rt["mf"] = mf_scores(sp, *mf_cfg)
    comps["mf"] = (S, v)
    S, v, rt["cbf"] = cbf_scores(sp, parts)
    comps["cbf"] = (S, v)
    S, v, rt["ar"] = ar_scores(sp)
    comps["ar"] = (S, v)
    return comps, rt


def main():
    T0 = time.time()
    md = ["# Phase B/C results (generated by src/hybrid.py)\n"]
    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    sps_ = {s: B.make_split(s, itx, HIST_MIN_SEC, users) for s in B.SPLITS}
    fb = {s: B.popularity(sp) for s, sp in sps_.items()}

    # ---------------- MF grid on main
    rows = []
    for f, r, a in MF_GRID:
        S, v, info = mf_scores(sps_["main"], f, r, a, 15, 0)
        m = mapk(sps_["main"].target, SC.topk(S, v, sps_["main"], fb["main"]))
        rows.append({"factors": f, "reg": r, "alpha": a, "MAP@5_main": m, **info})
        print(rows[-1])
    grid = pd.DataFrame(rows).sort_values("MAP@5_main", ascending=False)
    best = grid.iloc[0]
    mf_cfg = (int(best.factors), float(best.reg), float(best.alpha), 15, 0)
    S, v, _ = mf_scores(sps_["secondary"], *mf_cfg)
    mf_sec = mapk(sps_["secondary"].target, SC.topk(S, v, sps_["secondary"], fb["secondary"]))
    grid.to_csv(RES / "mf_grid.csv", index=False)
    md += ["## MF (ALS) grid on MAIN (15 iterations, seed 0)\n", grid.to_markdown(index=False, floatfmt=".5f"),
           f"\nChosen: factors={mf_cfg[0]}, reg={mf_cfg[1]}, alpha={mf_cfg[2]}; "
           f"secondary MAP@5 = {mf_sec:.5f}\n"]

    # ---------------- components on both splits
    comps, rts = {}, {}
    for s, sp in sps_.items():
        comps[s], rts[s] = components(sp, mf_cfg, VAL_PARTS)

    # ---------------- hybrid weight grid on main
    hrows = []
    sp = sps_["main"]
    for wm, wc, wa in itertools.product(W_MF, W_CBF, W_AR):
        w = {"pers": 1.0, "mf": wm, "cbf": wc, "ar": wa}
        S, V = fuse(comps["main"], w)
        hrows.append({"w_pers": 1.0, "w_mf": wm, "w_cbf": wc, "w_ar": wa,
                      "MAP@5_main": mapk(sp.target, SC.topk(S, V, sp, fb["main"]))})
    hg = pd.DataFrame(hrows).sort_values(["MAP@5_main", "w_mf", "w_cbf", "w_ar"],
                                         ascending=[False, True, True, True])
    hg.to_csv(RES / "hybrid_grid.csv", index=False)
    hb = hg.iloc[0]
    W = {"pers": 1.0, "mf": float(hb.w_mf), "cbf": float(hb.w_cbf), "ar": float(hb.w_ar)}
    md += ["## Hybrid weight grid on MAIN (top 15 of "
           f"{len(hg)}; w_pers fixed at 1)\n", hg.head(15).to_markdown(index=False, floatfmt=".5f"),
           f"\nChosen weights: {W}\n"]

    # ---------------- comparison table
    table, preds_main = [], {}
    for s, sp in sps_.items():
        bm = B.methods(sp)
        cand = {}
        for name, key in [("Popularity (pool, seconds)", "b_pop_pool"),
                          ("Popularity (pool, half-life 1 wk)", "c_pop_pool_hl1")]:
            t = time.time()
            cand[name] = (bm[key](), {"fit_s": time.time() - t, "predict_s": 0.0})
        c = comps[s]
        for name, k, rk in [("Personal history", "pers", "personal"), ("MF (ALS)", "mf", "mf"),
                            ("CBF", "cbf", "cbf"), ("Assoc. rules", "ar", "ar")]:
            t = time.time()
            p = SC.topk(*c[k], sp, fb[s])
            cand[name] = (p, {**rts[s][rk], "predict_s": rts[s][rk]["predict_s"] + time.time() - t})
        t = time.time()
        p = SC.topk(*fuse(c, W), sp, fb[s])
        hyb_rt = {"fit_s": sum(rts[s][k]["fit_s"] for k in ("personal", "mf", "cbf", "ar")),
                  "predict_s": time.time() - t}
        cand["Hybrid"] = (p, hyb_rt)
        for name, (p, rt) in cand.items():
            B.check_preds(p, sp.users, sp.pool)
            us, ap = SC.ap_per_user(sp.target, p)
            lo, hi = SC.bootstrap_ci(ap)
            table.append({"split": s, "method": name, "MAP@5": ap.mean(), "CI95_lo": lo, "CI95_hi": hi,
                          "fit_s": rt["fit_s"], "predict_s": rt["predict_s"], "n_users": len(ap)})
            if s == "main":
                preds_main[name] = p
    comp = pd.DataFrame(table)
    comp.to_csv(RES / "comparison.csv", index=False)
    wide = comp.pivot(index="method", columns="split", values="MAP@5")
    ci = comp[comp.split == "main"].set_index("method")
    wide["main 95% CI"] = [f"[{ci.loc[m, 'CI95_lo']:.4f}, {ci.loc[m, 'CI95_hi']:.4f}]" for m in wide.index]
    cis = comp[comp.split == "secondary"].set_index("method")
    wide["secondary 95% CI"] = [f"[{cis.loc[m, 'CI95_lo']:.4f}, {cis.loc[m, 'CI95_hi']:.4f}]" for m in wide.index]
    rtm = comp[comp.split == "main"].set_index("method")[["fit_s", "predict_s"]]
    wide = wide.join(rtm.rename(columns=lambda c: c + "_main")).sort_values("main", ascending=False)
    md += ["## Comparison (MAP@5; bootstrap over users, 1000 resamples, seed 0)\n",
           wide[["main", "main 95% CI", "secondary", "secondary 95% CI", "fit_s_main", "predict_s_main"]]
           .to_markdown(floatfmt=".5f"), ""]
    # paired bootstrap: hybrid - personal on main
    _, ap_h = SC.ap_per_user(sps_["main"].target, preds_main["Hybrid"])
    _, ap_p = SC.ap_per_user(sps_["main"].target, preds_main["Personal history"])
    d = ap_h - ap_p
    lo, hi = SC.bootstrap_ci(d)
    md += [f"Paired bootstrap, Hybrid − Personal history on main: mean {d.mean():+.5f}, "
           f"95% CI [{lo:+.5f}, {hi:+.5f}]\n",
           f"CBF: {rts['main']['cbf']['n_items']} items x {rts['main']['cbf']['n_features']} features (main). "
           f"AR: {rts['main']['ar']['n_rules']} rules from {rts['main']['ar']['n_transactions']} transactions "
           f"(set >= {SET_MIN_SEC}s, support >= {MIN_SUPPORT}, confidence >= {MIN_CONF}).\n"]

    # ---------------- final strategy
    main_tab = comp[comp.split == "main"].set_index("method")["MAP@5"]
    final_name = "Hybrid" if main_tab["Hybrid"] > main_tab["Personal history"] else "Personal history"
    t = time.time()
    hist = join.user_show_week(join.watched(itx, min_sec=HIST_MIN_SEC))
    hist = hist[hist.week.between(11, 30)]
    pool = B.pool_from_schedule(("31-42",), range(31, 43))
    spf = B.Split("final", hist, pool, users, {}, 30)
    cf, rtf = components(spf, mf_cfg, ("11-20", "21-30", "31-42"))
    fbf = B.popularity(spf)
    Wf = W if final_name == "Hybrid" else {"pers": 1.0}
    pf = SC.topk(*fuse(cf, Wf), spf, fbf)
    B.check_preds(pf, users, pool)
    out = RES / "submission_final.csv"
    sub = data.load_submission()
    out.write_text("user_id,tv_show_id\n" + "\n".join(f"{u},{' '.join(map(str, pf[u]))}" for u in sub.user_id))
    validate(out, pool)
    base = pd.read_csv(RES / "submission_baseline.csv", dtype=str)
    fin = pd.read_csv(out, dtype=str)
    same = (base.tv_show_id == fin.tv_show_id).mean()
    overlap = np.mean([len(set(a.split()) & set(b.split())) / 5 for a, b in zip(base.tv_show_id, fin.tv_show_id)])
    md += [f"## Final submission\n", f"Strategy: **{final_name}** with weights {Wf}, MF {mf_cfg}; "
           f"retrained on weeks 11-30, pool = {len(pool):,} shows from 31-42 schedule; "
           f"validated OK; runtime {time.time() - t:.1f}s. Rows identical to baseline: {same:.1%}; "
           f"mean item overlap with baseline: {overlap:.1%}.\n"]

    # ---------------- example users
    titles = item_table(("11-20", "21-30", "31-42"))[["tv_show_title", "tv_show_category"]]
    spm = sps_["main"]
    hsec = spm.hist.groupby("user_id").sec.sum()
    nshow = spm.hist.groupby("user_id").tv_show_id.nunique()
    ev = [u for u in spm.target if u in hsec.index]
    heavy = max(ev, key=lambda u: hsec[u])
    light = min(ev, key=lambda u: hsec[u])
    tw = B.SPLITS["main"][1]
    w = join.watched(itx, min_sec=B.TARGET_MIN_SEC)
    w = w[w.week.isin(list(tw))]
    ex = ["# Example users (main split; generated by src/hybrid.py)\n",
          "Selection rule: among main-split eval users with any history in weeks 11-20, "
          "heavy = maximum total labelled overlap seconds in history, light = minimum.\n"]

    def lab(i):
        if i in titles.index:
            return str(titles.loc[i, "tv_show_title"])[:60], str(titles.loc[i, "tv_show_category"])
        return "?", "?"

    for tag, u in (("Heavy viewer", heavy), ("Light viewer", light)):
        uh = spm.hist[spm.hist.user_id == u].groupby("tv_show_id").sec.sum().sort_values(ascending=False)
        ex += [f"## {tag}: user {u}\n",
               f"History weeks 11-20: {hsec[u]:,} s ({hsec[u] / 3600:.1f} h) over {nshow[u]} distinct labelled shows.\n",
               "Top history shows:\n",
               pd.DataFrame([(i, *lab(i), int(s)) for i, s in uh.head(5).items()],
                            columns=["tv_show_id", "title", "category", "seconds"]).to_markdown(index=False), ""]
        tt = w[w.user_id == u].groupby("tv_show_id").overlap_s.sum().sort_values(ascending=False).head(5)
        truth = set(spm.target[u])
        ex += ["Truth (top-5 watched in weeks 21-30):\n",
               pd.DataFrame([(i, *lab(i), int(s)) for i, s in tt.items()],
                            columns=["tv_show_id", "title", "category", "seconds"]).to_markdown(index=False), ""]
        for name, p in preds_main.items():
            r = p[u]
            ex += [f"**{name}** (AP@5 = {apk(spm.target[u], r):.3f}):\n",
                   pd.DataFrame([(k + 1, i, *lab(i), "✓" if i in truth else "") for k, i in enumerate(r)],
                                columns=["rank", "tv_show_id", "title", "category", "hit"]).to_markdown(index=False), ""]
        ex += [f"**Final strategy ({final_name}), weeks 31-42 Top-5:**\n",
               pd.DataFrame([(k + 1, i, *lab(i)) for k, i in enumerate(pf[u])],
                            columns=["rank", "tv_show_id", "title", "category"]).to_markdown(index=False), ""]
    (RES / "examples.md").write_text("\n".join(ex) + "\n")
    md.append(f"Total runtime {time.time() - T0:.1f}s")
    (RES / "phaseBC.md").write_text("\n".join(md) + "\n")
    json.dump({"mf_cfg": mf_cfg, "weights": W, "final": final_name, "heavy": int(heavy), "light": int(light)},
              open(RES / "phaseBC_choices.json", "w"), indent=1)
    print("\n".join(md))


if __name__ == "__main__":
    main()
