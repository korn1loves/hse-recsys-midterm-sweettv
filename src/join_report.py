"""Phase A step 3 report: time alignment, labelled share, overlap distributions, hand example.
Writes results/join_report.md and results/fig_overlap.png."""
import time

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

import data
import join

OUT = data.ROOT / "results" / "join_report.md"
FIG = data.ROOT / "results" / "fig_overlap.png"
lines = []


def out(s=""):
    print(s)
    lines.append(s)


def near_start_share(log, sched, shift_s, tol=30):
    """Share of view starts within +-tol s of some airing start on the same channel."""
    key_a = sched.channel_id.values.astype(np.int64) * 10**10 + \
        sched.start_time.values.astype("datetime64[s]").astype(np.int64)
    key_a = np.sort(key_a)
    key_v = log.vsetv_id.values.astype(np.int64) * 10**10 + \
        log.start_time.values.astype("datetime64[s]").astype(np.int64) + shift_s
    i = np.searchsorted(key_a, key_v)
    d = np.full(len(key_v), np.inf)
    for j in (i - 1, i):
        jj = np.clip(j, 0, len(key_a) - 1)
        d = np.minimum(d, np.abs(key_v - key_a[jj]))
    return (d <= tol).mean()


def main():
    t0 = time.time()
    log = data.load_log().drop_duplicates()
    sched = join.schedule_for(("11-20", "21-30"))

    out("# Join report (generated by src/join_report.py)\n")
    out("## Time alignment of log vs schedule\n")
    out("Share of view start_times within ±30 s of an airing start on the same channel, "
        "after shifting view times by s (zapping clusters at programme starts, so the true "
        "alignment should maximise this):\n")
    rows = []
    periods = {"all": slice(None), "weeks 11-13 (before 2020-03-29 DST)": log.week <= 13,
               "weeks 14-30": log.week >= 14}
    for s in (-7200, -3600, -600, 0, 600, 3600, 7200):
        rows.append({"shift_s": s, **{k: near_start_share(log[m] if not isinstance(m, slice) else log,
                                                          sched, s) for k, m in periods.items()}})
    out(pd.DataFrame(rows).set_index("shift_s").map(lambda x: f"{x:.2%}").to_markdown())
    out("")

    t1 = time.time()
    itx = join.airing_interactions(force=True)
    out(f"Join runtime (build + aggregate): {time.time() - t1:.1f}s; "
        f"(user, airing, week) rows: {len(itx):,}\n")

    # --- share of viewing time
    tot = log.duraton.sum()
    lab = itx.tv_show_id != 0
    s_lab, s_unl = itx.overlap_s[lab].sum(), itx.overlap_s[~lab].sum()
    out("## Where viewing time falls\n")
    out(f"- total viewing seconds in log (deduplicated rows): {tot:,} ({tot / 3600:,.0f} h)")
    out(f"- on labelled airings (tv_show_id != 0): {s_lab / tot:.2%}")
    out(f"- on unlabelled airtime (tv_show_id == 0): {s_unl / tot:.2%}")
    out(f"- not covered by any airing (channel missing from schedule / gaps / caps): "
        f"{1 - (s_lab + s_unl) / tot:.2%}")
    sub_u = set(data.load_submission().user_id)
    su = itx.user_id.isin(sub_u)
    sl = log.user_id.isin(sub_u)
    out(f"- submission users only: labelled {itx.overlap_s[lab & su].sum() / log.duraton[sl].sum():.2%}, "
        f"unlabelled {itx.overlap_s[~lab & su].sum() / log.duraton[sl].sum():.2%}")
    li = itx[lab]
    out(f"- labelled (user, airing, week) rows: {len(li):,}; users with any labelled overlap: "
        f"{li.user_id.nunique():,}/{log.user_id.nunique():,}; "
        f"submission users with any labelled overlap: {li.user_id[li.user_id.isin(sub_u)].nunique():,}/1,260")
    out("")

    # --- distributions
    qs = [.05, .1, .25, .5, .75, .9, .95, .99]
    out("## Distribution of labelled per-airing overlap (user x airing)\n")
    dist = pd.DataFrame({"overlap_s": li.overlap_s.quantile(qs), "frac": li.frac.quantile(qs).round(3)}).T
    dist.columns = [f"q{x:g}" for x in qs]
    out(dist.to_markdown())
    out("")
    cuts = [0, 60, 120, 300, 600, 900, 1800, 3600, 10**9]
    b = pd.cut(li.overlap_s, cuts, right=False)
    tab = pd.DataFrame({"airings": b.value_counts(sort=False),
                        "share_airings": b.value_counts(normalize=True, sort=False),
                        "share_seconds": li.overlap_s.groupby(b, observed=False).sum() / li.overlap_s.sum()})
    out("Overlap bins (left-closed):\n")
    out(tab.to_markdown(floatfmt=".4f"))
    out("")
    fb = pd.cut(li.frac, [0, .05, .1, .25, .5, .75, .9, 1.0001], right=False)
    tabf = pd.DataFrame({"airings": fb.value_counts(sort=False),
                         "share_airings": fb.value_counts(normalize=True, sort=False),
                         "share_seconds": li.overlap_s.groupby(fb, observed=False).sum() / li.overlap_s.sum()})
    out("Overlap / airing duration bins:\n")
    out(tabf.to_markdown(floatfmt=".4f"))
    out("")
    # candidate thresholds
    out("Effect of candidate 'watched' thresholds on labelled airings:\n")
    rows = []
    for ms, mf in [(0, 0), (60, 0), (120, 0), (300, 0), (600, 0), (300, .5), (900, 0), (0, .25), (0, .5)]:
        if ms == 0 and mf > 0:
            k = li.frac >= mf
            name = f"frac>={mf}"
        else:
            k = (li.overlap_s >= ms) | ((li.frac >= mf) if mf > 0 else False)
            name = f">={ms}s" + (f" OR frac>={mf}" if mf > 0 else "")
        uw = li[k].groupby(["user_id", "tv_show_id"]).size()
        rows.append({"rule": name, "airings_kept": k.mean(),
                     "seconds_kept": li.overlap_s[k].sum() / li.overlap_s.sum(),
                     "user_show_pairs": len(uw),
                     "sub_users_with_any": li[k].user_id[li[k].user_id.isin(sub_u)].nunique()})
    out(pd.DataFrame(rows).set_index("rule").to_markdown(floatfmt=".4f"))
    out("")

    fig, ax = plt.subplots(1, 2, figsize=(11, 3.8))
    ax[0].hist(np.log10(li.overlap_s.clip(lower=1)), bins=80, weights=None, color="#4c72b0")
    ax[0].set_xlabel("log10 overlap seconds (user x labelled airing)")
    ax[0].set_ylabel("airings")
    for v in (60, 300, 900):
        ax[0].axvline(np.log10(v), color="k", ls=":", lw=1)
    ax[1].hist(li.frac, bins=50, color="#55a868", weights=li.overlap_s / 3600)
    ax[1].set_xlabel("overlap / airing duration")
    ax[1].set_ylabel("hours of viewing (weighted)")
    fig.tight_layout()
    fig.savefig(FIG, dpi=120)
    out(f"Figure: `results/{FIG.name}` (left: log overlap with 60/300/900 s marks; "
        "right: fraction watched, weighted by seconds).\n")

    # --- hand-checkable example
    out("## Hand-checkable example\n")
    rng = np.random.default_rng(0)
    cand = log[(log.duraton.between(1500, 4000))]
    for _ in range(50):
        v = cand.iloc[rng.integers(len(cand))]
        a = sched[(sched.channel_id == v.vsetv_id) & (sched.end_time > v.start_time) &
                  (sched.start_time < v.stop_time)]
        if (a.tv_show_id != 0).any() and len(a) >= 2:
            break
    out(f"View: user {v.user_id}, channel {v.vsetv_id}, {v.start_time} -> {v.stop_time} "
        f"(duraton {v.duraton}s, ISO week {v.week}).\n")
    a = a.copy()
    a["overlap_manual_s"] = [(min(v.stop_time, e) - max(v.start_time, s)).total_seconds()
                             for s, e in zip(a.start_time, a.end_time)]
    p = join.overlap_pairs(log.loc[[v.name]], sched)
    a = a.merge(p[["airing_id", "overlap_s"]].rename(columns={"overlap_s": "overlap_join_s"}),
                on="airing_id", how="left")
    out(a[["airing_id", "start_time", "end_time", "duration", "tv_show_id", "tv_show_title",
           "overlap_manual_s", "overlap_join_s"]].to_markdown(index=False))
    out(f"\nSum of overlaps = {a.overlap_manual_s.sum():.0f}s vs duraton {v.duraton}s "
        "(equal unless the view runs over a schedule gap).\n")
    out(f"runtime {time.time() - t0:.1f}s")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
