"""Phase G driver: title-family statistics, family personal / family rate components, family fallback.
Writes results/phaseG.md, results/phaseG_grid.csv, results/phaseG_manifest.csv, results/submission_g0*.csv."""
import time

import numpy as np
import pandas as pd

import baselines as B
import data
import join
import phase_d as PD
import scoring as SC
from exposure import show_airtime
from family import family_fallback, family_scores, id_families
from phase_e import BASE, VP, components, fuse

RES = data.ROOT / "results"
F03 = {**BASE, "daypart_4": 1.0, "channel_4": 0.5}


def stats(fi):
    md = ["### Family statistics\n"]
    sizes = fi.groupby("family").size()
    md.append(f"- labelled ids: {len(fi):,}; families: {fi.family.nunique():,}; families with >= 2 ids: "
              f"{(sizes >= 2).sum():,} covering {sizes[sizes >= 2].sum():,} ids\n")
    top = sizes.sort_values(ascending=False).head(20)
    rows = []
    for f, n in top.items():
        g = fi[fi.family == f]
        rows.append({"family": f, "n_ids": n, "categories": ", ".join(sorted(g.category.dropna().unique()))[:40],
                     "example titles": " | ".join(g.tv_show_title.head(3).str[:40])})
    md += ["20 largest families:\n", pd.DataFrame(rows).to_markdown(index=False), ""]

    s_old = data.load_schedule_all(VP)
    s_new = data.load_schedule("31-42")
    old_ids = set(s_old.tv_show_id[s_old.tv_show_id != 0])
    new = s_new[(s_new.tv_show_id != 0) & s_new.week.between(31, 42)].tv_show_id.unique()
    new_ids = [i for i in new if i not in old_ids]
    old_fams = set(fi.family.reindex(list(old_ids)).dropna())
    joined = [i for i in new_ids if fi.family.get(i) in old_fams]
    md.append(f"- labelled ids airing in weeks 31-42 that never appear in the 11-30 schedules: {len(new_ids):,}; "
              f"of these, joining a family seen in 11-30: **{len(joined):,}** ({len(joined) / len(new_ids):.1%})")

    # merged examples
    rng = np.random.default_rng(0)
    multi = fi[fi.family.map(sizes) >= 2]
    ex = multi.iloc[rng.choice(len(multi), 15, replace=False)]
    rows = [{"tv_show_id": i, "title": r.tv_show_title[:45], "family": r.family,
             "other ids' titles": " | ".join(fi[(fi.family == r.family) & (fi.index != i)].tv_show_title.head(2).str[:35])}
            for i, r in ex.iterrows()]
    md += ["", "15 random merged ids (seed 0):\n", pd.DataFrame(rows).to_markdown(index=False), ""]

    # suspicious merges: families mixing categories, or un-prefixed one-word keys with several ids
    cats = multi.groupby("family").category.nunique()
    oneword = [f for f in sizes[sizes >= 2].index if " " not in f and "/" not in f]
    md.append(f"- possible wrong merges: families with >= 2 ids mixing categories: {(cats > 1).sum():,} "
              f"(e.g. {', '.join(cats[cats > 1].index[:8])}); un-prefixed one-word keys with >= 2 ids: "
              f"{len(oneword):,} (e.g. {', '.join(oneword[:10])})\n")
    return md, set(new_ids), set(joined)


def target_stats(sp, fi, hist_weeks):
    s = data.load_schedule_all(VP)
    hist_ids = set(s.tv_show_id[(s.tv_show_id != 0) & s.week.isin(list(hist_weeks))])
    hist_fams = set(fi.family.reindex(list(hist_ids)).dropna())
    ufam = sp.hist.assign(f=fi.family.reindex(sp.hist.tv_show_id).values).groupby("user_id").f.agg(set).to_dict()
    n = new = joins = user_joins = 0
    for u, items in sp.target.items():
        for i in items:
            n += 1
            if i not in hist_ids:
                new += 1
                f = fi.family.get(i)
                joins += f in hist_fams
                user_joins += f in ufam.get(u, set())
    return (f"- {sp.name}: target items {n:,}; ids not airing in history weeks {new:,} ({new / n:.1%}); "
            f"of these joining a history family {joins:,}; joining a family THE USER watched in history {user_joins:,}")


def main():
    T0 = time.time()
    fi = id_families()
    fam = fi.family
    md = ["## 13. Phase G: title families (generated by src/phase_g.py)\n"]
    smd, _, _ = stats(fi)
    md += smd

    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    sp, comps, fbs = {}, {}, {}
    tlines = []
    for s, (hw, tw) in B.SPLITS.items():
        sp[s] = B.make_split(s, itx, 0, users)
        comps[s], _ = components(sp[s], list(hw), list(tw), VP, VP)
        comps[s]["famP"] = family_scores(sp[s], fam)
        comps[s]["famR"] = family_scores(sp[s], fam, rate=True, hist_air=show_airtime(VP, hw),
                                         target_air=show_airtime(VP, tw))
        fbs[s] = {"id": B.popularity(sp[s]), "family": family_fallback(sp[s], fam)}
        tlines.append(target_stats(sp[s], fi, hw))
    md += ["Validation target items reachable through families:\n"] + tlines + [""]

    def ap(s, w, fb):
        return SC.ap_per_user(sp[s].target, SC.topk(*fuse(comps[s], w), sp[s], fbs[s][fb]))[1]

    configs = {"f03 (reference)": (F03, "id"), "famP alone": ({"famP": 1.0}, "id"),
               "famR alone": ({"famR": 1.0}, "id"), "pers alone": ({"pers": 1.0}, "id")}
    for c in ("famP", "famR"):
        for wt in (0.5, 1.0, 2.0):
            configs[f"f03 + {c} {wt:g}"] = ({**F03, c: wt}, "id")
        configs[f"f03, pers -> {c}"] = ({**{k: v for k, v in F03.items() if k != "pers"}, c: 1.0}, "id")
    # ablations: is the family gain just more weight on the personal/rate signal?
    configs["ablation: f03 with id-rate 1.25"] = ({**F03, "rate": 1.25}, "id")
    configs["ablation: f03 with pers 2"] = ({**F03, "pers": 2.0}, "id")
    ref = {s: ap(s, F03, "id") for s in sp}
    rows = []

    def run(name, w, fb):
        r = {"config": name, "fallback": fb}
        for s in sp:
            a = ap(s, w, fb)
            d = a - ref[s]
            lo, hi = SC.bootstrap_ci(d)
            r[s] = a.mean()
            r[f"Δ {s} vs f03"] = f"{d.mean():+.5f} [{lo:+.5f}, {hi:+.5f}]"
        r["mean"] = (r["main"] + r["secondary"]) / 2
        r["_w"] = w
        rows.append(r)

    for name, (w, fb) in configs.items():
        run(name, w, fb)
    g = pd.DataFrame(rows)
    add = g[g.config.str.startswith("f03 + ")].sort_values("mean", ascending=False).iloc[0]
    rep = g[g.config.str.startswith("f03, pers")].sort_values("mean", ascending=False).iloc[0]
    for name, w in [("f03", F03), (add.config, add._w), (rep.config, rep._w)]:
        run(f"{name} + family fallback", w, "family")
    g = pd.DataFrame(rows)
    fbv = g[g.fallback == "family"].sort_values("mean", ascending=False).iloc[0]
    g.drop(columns="_w").to_csv(RES / "phaseG_grid.csv", index=False)
    md += ["Results (MAP@5; Δ = paired bootstrap vs f03, 1000 resamples, seed 0):\n",
           g.drop(columns="_w").sort_values("mean", ascending=False).to_markdown(index=False, floatfmt=".5f"), ""]

    # final files
    t = time.time()
    hist = join.user_show_week(join.watched(itx, min_sec=0))
    hist = hist[hist.week.between(11, 30)]
    pool = B.pool_from_schedule(("31-42",), range(31, 43))
    spf = B.Split("final", hist, pool, users, {}, 30)
    cf, _ = components(spf, list(range(11, 31)), list(range(31, 43)), VP, ("31-42",))
    cf["famP"] = family_scores(spf, fam)
    cf["famR"] = family_scores(spf, fam, rate=True, hist_air=show_airtime(VP, range(11, 31)),
                               target_air=show_airtime(("31-42",), range(31, 43)))
    fbf = {"id": B.popularity(spf), "family": family_fallback(spf, fam)}
    picks = [(add, "f03 + family at best weight by mean"), (rep, "family replaces pers (best by mean)"),
             (fbv, "best family-fallback variant by mean"),
             (g[g.config == "ablation: f03 with id-rate 1.25"].iloc[0], "ablation: same gain without families?")]
    man, seen, dup_notes = [], [], []
    for r, why in picks:
        p = SC.topk(*fuse(cf, r._w), spf, fbf[r.fallback])
        B.check_preds(p, users, pool)
        same = [m["file"] for m, q in seen if q == p]
        if same:
            dup_notes.append(f"- `{r.config}` ({r.fallback} fallback; {why}) gives predictions identical to "
                             f"{same[0]} on the final refit -> not written.")
            continue
        fn = f"submission_g{len(man) + 1:02d}.csv"
        PD.write_sub(p, pool, fn)
        x = pd.read_csv(RES / fn, dtype=str).tv_show_id.str.split()
        y = pd.read_csv(RES / "submission_f03.csv", dtype=str).tv_show_id.str.split()
        ov = sum(len(set(a) & set(b)) for a, b in zip(x, y)) / (5 * len(x))
        man.append({"file": f"results/{fn}", "config": r.config, "fallback": r.fallback,
                    "weights": " ".join(f"{k}={v:g}" for k, v in r._w.items()),
                    "main": round(r.main, 5), "secondary": round(r.secondary, 5), "mean": round(r["mean"], 5),
                    "overlap_with_f03": round(ov, 3), "why": why})
        seen.append((man[-1], p))
    man = pd.DataFrame(man)
    man.to_csv(RES / "phaseG_manifest.csv", index=False)
    md += [f"Candidate files (refit weeks 11-30, pool {len(pool):,} from the 31-42 schedule, validated; "
           f"{time.time() - t:.1f}s):\n", man.to_markdown(index=False), ""] + dup_notes + ["",
           f"Phase G runtime {time.time() - T0:.1f}s\n"]
    (RES / "phaseG.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
