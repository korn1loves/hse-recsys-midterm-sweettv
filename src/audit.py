"""Phase A step 2: data audit. Writes results/audit.md."""
import datetime as dt
import sys
import time

import numpy as np
import pandas as pd

import data

OUT = data.ROOT / "results" / "audit.md"
lines = []


def out(s=""):
    print(s)
    lines.append(s)


def table(df: pd.DataFrame):
    out(df.to_markdown() if hasattr(df, "to_markdown") else "```\n" + df.to_string() + "\n```")


def q(s: pd.Series, qs=(0, .01, .05, .1, .25, .5, .75, .9, .95, .99, 1)):
    return s.quantile(list(qs)).rename(lambda x: f"q{x:g}")


def iso_monday(year, week):
    return dt.date.fromisocalendar(year, week, 1)


def main():
    t0 = time.time()
    log = data.load_log()
    sched = {p: data.load_schedule(p) for p in data.SCHED_FILES}
    sub = data.load_submission()

    out("# Data audit (generated by src/audit.py)\n")

    # ---- raw formats
    out("## Raw timestamp formats (first data line of each file)\n")
    for name in ["dataset11-30.csv", *data.SCHED_FILES.values()]:
        with open(data.DATA / name, encoding="utf-8") as f:
            f.readline()
            out(f"- `{name}`: `{f.readline().strip()[:110]}`")
    out(f"\nParsed with explicit formats: log `{data.LOG_FMT}`, schedules `{data.SCHED_FMT}` "
        "(pd.to_datetime(format=...) raises on any non-matching value, so all rows matched).\n")

    # ---- log
    out("## View log `dataset11-30.csv`\n")
    out(f"- rows: {len(log):,}; columns: {list(log.columns[:5])}")
    out(f"- dtypes: " + ", ".join(f"{c}={t}" for c, t in log.dtypes.items()))
    out(f"- nulls: {int(log.isna().sum().sum())}")
    out(f"- start_time: {log.start_time.min()} .. {log.start_time.max()}")
    out(f"- stop_time: {log.stop_time.min()} .. {log.stop_time.max()}")
    out(f"- users: {log.user_id.nunique():,}; channels (vsetv_id): {log.vsetv_id.nunique()}")
    diff = (log.stop_time - log.start_time).dt.total_seconds()
    out(f"- duraton == stop-start: {(diff == log.duraton).mean():.4%} of rows; "
        f"max |diff| = {(diff - log.duraton).abs().max():.0f}s")
    out(f"- rows with duraton <= 0: {(log.duraton <= 0).sum():,}")
    out(f"- exact duplicate rows: {log.duplicated().sum():,}")
    out(f"- views crossing midnight Sunday->Monday (start week != stop week): "
        f"{(data.iso_week(log.stop_time) != log.week).sum():,}")
    out("\nduraton (seconds) quantiles:\n")
    table(q(log.duraton).to_frame("duraton").T)
    out(f"\nmean {log.duraton.mean():.1f}s; share <60s {(log.duraton < 60).mean():.2%}; "
        f"share >4h {(log.duraton > 4 * 3600).mean():.2%}\n")

    # ISO week check
    out("Rows / users per ISO week of view start_time:\n")
    w = log.groupby("week").agg(rows=("user_id", "size"), users=("user_id", "nunique"),
                                first=("start_time", "min"), last=("start_time", "max"))
    w["iso_monday"] = [iso_monday(2020, int(k)) for k in w.index]
    table(w)
    out("")

    # ---- schedules
    out("## Schedules `export_arh_*`\n")
    for p, s in sched.items():
        out(f"### {data.SCHED_FILES[p]}\n")
        out(f"- rows: {len(s):,}; columns: {len(s.columns) - 2} raw (+ derived end_time, week)")
        out(f"- start_time: {s.start_time.min()} .. {s.start_time.max()}; "
            f"end_time max {s.end_time.max()}")
        wk = s.week.agg(["min", "max"])
        out(f"- ISO weeks of airing start: {wk['min']}..{wk['max']}; "
            f"Monday of first week {iso_monday(2020, int(wk['min']))}, "
            f"Sunday of last week {iso_monday(2020, int(wk['max'])) + dt.timedelta(days=6)}")
        out(f"- rows per week: {s.week.value_counts().sort_index().to_dict()}")
        out(f"- channels: {s.channel_id.nunique()}; distinct tv_show_id != 0: "
            f"{s.loc[s.tv_show_id != 0, 'tv_show_id'].nunique():,}")
        lab = s.tv_show_id != 0
        out(f"- share of rows with tv_show_id != 0: {lab.mean():.2%}; "
            f"share of airtime (duration) labelled: "
            f"{s.loc[lab, 'duration'].sum() / s.duration.sum():.2%}")
        out(f"- duration <= 0: {(s.duration <= 0).sum():,}; exact duplicate rows: {s.duplicated().sum():,}")
        # overlap between consecutive airings on a channel
        ss = s.sort_values(["channel_id", "start_time"])
        nxt = ss.groupby("channel_id").start_time.shift(-1)
        ov = (ss.end_time - nxt).dt.total_seconds()
        out(f"- consecutive airings on a channel that overlap: {(ov > 0).sum():,} "
            f"({(ov > 0).mean():.2%}); gaps (>0s): {(ov < 0).sum():,}; "
            f"median gap {(-ov[ov < 0]).median() if (ov < 0).any() else 0:.0f}s")
        out("\nschedule duration quantiles (s), all rows vs labelled rows:\n")
        table(pd.DataFrame({"all": q(s.duration), "labelled": q(s.loc[lab, "duration"])}).T)
        out("\nnull share of metadata columns (labelled rows):\n")
        table(s.loc[lab, ["tv_show_category", "tv_show_genre_1", "tv_show_genre_2", "tv_show_genre_3",
                          "year_of_production", "director", "actors"]].isna().mean()
              .to_frame("null_share").T.round(3))
        out("")

    # channels consistency
    lc = set(log.vsetv_id.unique())
    for p, s in sched.items():
        sc = set(s.channel_id.unique())
        out(f"- log channels in schedule {p}: {len(lc & sc)}/{len(lc)}; "
            f"schedule channels not in log: {len(sc - lc)}")
    ids = {p: set(s.loc[s.tv_show_id != 0, "tv_show_id"]) for p, s in sched.items()}
    out(f"- labelled shows 11-20 ∩ 21-30: {len(ids['11-20'] & ids['21-30']):,}; "
        f"31-42 shows also in 11-30: {len(ids['31-42'] & (ids['11-20'] | ids['21-30'])):,}"
        f"/{len(ids['31-42']):,}")
    # title consistency of ids
    allsch = pd.concat(sched.values())
    lab = allsch[allsch.tv_show_id != 0]
    ntitles = lab.groupby("tv_show_id").tv_show_title.nunique()
    out(f"- tv_show_id with >1 distinct title: {(ntitles > 1).sum():,}/{len(ntitles):,} "
        f"(episode/season titles); max titles per id {ntitles.max()}\n")

    # ---- submission
    out("## submission.csv\n")
    with open(data.DATA / "submission.csv", "rb") as f:
        raw = f.read()
    out(f"- header: `{raw.splitlines()[0].decode()}`; data rows: {len(sub):,}; "
        f"distinct users: {sub.user_id.nunique():,}")
    out(f"- example row: `{raw.splitlines()[1].decode()}`; line ending "
        f"{'CRLF' if b'\r\n' in raw else 'LF'}; trailing newline at EOF: {raw.endswith(b'\n')}")
    su = set(sub.user_id)
    lu = log.groupby("user_id")
    in_log = su & set(log.user_id.unique())
    out(f"- submission users with any log rows: {len(in_log):,}/{len(su):,}")
    sub_log = log[log.user_id.isin(su)]
    out(f"- log rows of submission users: {len(sub_log):,} ({len(sub_log) / len(log):.2%} of log)")
    per_user = sub_log.groupby("user_id").agg(rows=("week", "size"), weeks=("week", "nunique"),
                                              hours=("duraton", lambda x: x.sum() / 3600))
    out("\nper submission user activity (11-30):\n")
    table(per_user.describe().T.round(1))
    out(f"\n(labelled-interaction counts per submission user are reported by src/join.py)\n")
    out(f"runtime {time.time() - t0:.1f}s")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
