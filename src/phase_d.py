"""Phase D driver: exposure (schedule-slot CBF) + rate-normalised personal history, hybrid re-tuning,
final refits. Writes results/phaseD.md, results/phaseD_comparison.csv, results/phaseD_hybrid_grid.csv,
results/phaseD_examples.md, results/submission_exposure.csv, results/submission_hybrid2.csv
(+ submission_hybrid3.csv if a near-tie on main is better on secondary)."""
import itertools
import json
import time

import numpy as np
import pandas as pd

import baselines as B
import data
import join
import scoring as SC
from ar import ar_scores
from cbf import item_table
from exposure import exposure_scores, rate_scores
from hybrid import fuse
from make_submission import validate
from metrics import apk, mapk
from mf import mf_scores

RES = data.ROOT / "results"
CH = json.load(open(RES / "phaseBC_choices.json"))
MF_CFG = tuple(CH["mf_cfg"])
OLD_W = CH["weights"]  # pers 1, mf 1, cbf 0, ar 0.25
HLS = [None, 4, 2]
GRID = dict(pers=[0, 1], rate=[0, 0.5, 1, 2], exp=[0, 0.25, 0.5, 1, 2], ar=[0, 0.25], mf=[0, 1])


def comps_for(sp, hist_weeks, target_weeks, hist_parts, target_parts):
    c, rt = {}, {}
    t = time.time()
    c["pers"] = SC.personal_scores(sp)
    rt["pers"] = {"fit_s": time.time() - t, "predict_s": 0.0}
    for hl in HLS:
        S, v, rt[f"exp_{hl}"] = exposure_scores(sp, hist_weeks, tuple(dict.fromkeys(hist_parts + target_parts)),
                                                target_weeks, hl)
        c[f"exp_{hl}"] = (S, v)
    S, v, rt["rate"] = rate_scores(sp, hist_parts, hist_weeks, target_parts, target_weeks)
    c["rate"] = (S, v)
    S, v, rt["ar"] = ar_scores(sp)
    c["ar"] = (S, v)
    S, v, rt["mf"] = mf_scores(sp, *MF_CFG)
    c["mf"] = (S, v)
    return c, rt


def write_sub(preds, pool, name):
    sub = data.load_submission()
    out = RES / name
    out.write_text("user_id,tv_show_id\n" + "\n".join(f"{u},{' '.join(map(str, preds[u]))}" for u in sub.user_id))
    validate(out, pool)
    return out


def main():
    T0 = time.time()
    itx = join.airing_interactions()
    users = data.load_submission().user_id.tolist()
    VP = ("11-20", "21-30")
    sp, comps, rts, fb = {}, {}, {}, {}
    for s, (hw, tw) in B.SPLITS.items():
        sp[s] = B.make_split(s, itx, 0, users)
        fb[s] = B.popularity(sp[s])
        comps[s], rts[s] = comps_for(sp[s], list(hw), list(tw), VP, VP)

    def evalp(s, S, V):
        return SC.topk(S, V, sp[s], fb[s])

    # ---- single methods
    md = ["## Phase D (generated by src/phase_d.py)\n"]
    rows, preds_main = [], {}
    labels = {"exp_None": "Exposure (no recency)", "exp_4": "Exposure (half-life 4 wk)",
              "exp_2": "Exposure (half-life 2 wk)", "rate": "Rate-normalised personal",
              "pers": "Personal history", "ar": "Assoc. rules", "mf": "MF (ALS)"}
    for s in sp:
        bm = B.methods(sp[s])
        single = {"Popularity (pool, seconds)": bm["b_pop_pool"]()}
        for k, lab in labels.items():
            single[lab] = evalp(s, *comps[s][k])
        single["Old hybrid (pers 1 + MF 1 + AR 0.25)"] = evalp(s, *fuse(comps[s], {k: v for k, v in OLD_W.items() if k != "cbf"}))
        for name, p in single.items():
            B.check_preds(p, sp[s].users, sp[s].pool)
            _, ap = SC.ap_per_user(sp[s].target, p)
            lo, hi = SC.bootstrap_ci(ap)
            rows.append({"split": s, "method": name, "MAP@5": ap.mean(), "lo": lo, "hi": hi})
            if s == "main":
                preds_main[name] = p
    single_df = pd.DataFrame(rows)
    best_exp = max(["exp_None", "exp_4", "exp_2"],
                   key=lambda k: single_df[(single_df.split == "main") & (single_df.method == labels[k])]["MAP@5"].iloc[0])

    # ---- hybrid grid on main
    hrows = []
    for wp, wr, we, wa, wm in itertools.product(*GRID.values()):
        if wp + wr + we + wa + wm == 0:
            continue
        w = {"pers": wp, "rate": wr, best_exp: we, "ar": wa, "mf": wm}
        hrows.append({"w_pers": wp, "w_rate": wr, "w_exp": we, "w_ar": wa, "w_mf": wm,
                      "MAP@5_main": mapk(sp["main"].target, evalp("main", *fuse(comps["main"], w)))})
    hg = pd.DataFrame(hrows).sort_values("MAP@5_main", ascending=False).reset_index(drop=True)
    wcols = ["w_pers", "w_rate", "w_exp", "w_ar", "w_mf"]
    tow = lambda r: {"pers": float(r.w_pers), "rate": float(r.w_rate), best_exp: float(r.w_exp), "ar": float(r.w_ar), "mf": float(r.w_mf)}
    near = hg[hg["MAP@5_main"] >= hg["MAP@5_main"].iloc[0] - 0.002].copy()
    near["MAP@5_secondary"] = [mapk(sp["secondary"].target, evalp("secondary", *fuse(comps["secondary"], tow(r))))
                               for r in near.itertuples()]
    hg = hg.merge(near[wcols + ["MAP@5_secondary"]], on=wcols, how="left")
    hg.to_csv(RES / "phaseD_hybrid_grid.csv", index=False)
    W2 = tow(hg.iloc[0])
    alt = near.sort_values("MAP@5_secondary", ascending=False).iloc[0]
    W3 = tow(alt) if alt["MAP@5_secondary"] > near.iloc[0]["MAP@5_secondary"] else None

    # ---- hybrid rows + paired bootstrap vs old hybrid
    paired = {}
    for s in sp:
        for name, w in [("Hybrid2", W2)] + ([("Hybrid3", W3)] if W3 else []):
            p = evalp(s, *fuse(comps[s], w))
            B.check_preds(p, sp[s].users, sp[s].pool)
            _, ap = SC.ap_per_user(sp[s].target, p)
            lo, hi = SC.bootstrap_ci(ap)
            rows.append({"split": s, "method": name, "MAP@5": ap.mean(), "lo": lo, "hi": hi})
            _, ap_old = SC.ap_per_user(sp[s].target, evalp(s, *fuse(comps[s], {k: v for k, v in OLD_W.items() if k != "cbf"})))
            paired[(s, name)] = ((ap - ap_old).mean(), *SC.bootstrap_ci(ap - ap_old))
            if s == "main":
                preds_main[name] = p
    comp = pd.DataFrame(rows)
    comp.to_csv(RES / "phaseD_comparison.csv", index=False)
    wide = comp.pivot(index="method", columns="split", values="MAP@5")
    for s in sp:
        c = comp[comp.split == s].set_index("method")
        wide[f"{s} 95% CI"] = [f"[{c.loc[m, 'lo']:.4f}, {c.loc[m, 'hi']:.4f}]" for m in wide.index]
    wide = wide[["main", "main 95% CI", "secondary", "secondary 95% CI"]].sort_values("main", ascending=False)

    rt = pd.DataFrame({k: v for k, v in rts["main"].items()}).T[["fit_s", "predict_s"]]
    md += ["Comparison (MAP@5, bootstrap 1000 resamples, seed 0):\n", wide.to_markdown(floatfmt=".5f"), "",
           f"Best exposure variant on main: `{best_exp}`.\n",
           f"Hybrid grid: {len(hg)} configs on main over {GRID} (exposure = {best_exp}). Top 10 "
           "(MAP@5_secondary computed only for configs within 0.002 of the best on main):\n",
           hg.head(10).to_markdown(index=False, floatfmt=".5f"), "",
           f"Chosen Hybrid2 weights: {W2}" + (f"; Hybrid3 (within 0.002 on main, better on secondary): {W3}" if W3 else
                                              "; no near-tie config is better on secondary -> no Hybrid3"), "",
           "Paired bootstrap vs old hybrid (mean diff, 95% CI):\n"]
    md += [f"- {n} on {s}: {d:+.5f} [{lo:+.5f}, {hi:+.5f}]" for (s, n), (d, lo, hi) in paired.items()]
    md += ["", "Component runtimes on main (s):\n", rt.to_markdown(floatfmt=".2f"), ""]

    # ---- final refits
    t = time.time()
    hist = join.user_show_week(join.watched(itx, min_sec=0))
    hist = hist[hist.week.between(11, 30)]
    pool = B.pool_from_schedule(("31-42",), range(31, 43))
    spf = B.Split("final", hist, pool, users, {}, 30)
    cf, _ = comps_for(spf, list(range(11, 31)), list(range(31, 43)), VP, ("31-42",))
    fbf = B.popularity(spf)
    finals = {"submission_exposure.csv": {best_exp: 1.0}, "submission_hybrid2.csv": W2}
    if W3:
        finals["submission_hybrid3.csv"] = W3
    final_preds = {}
    for fn, w in finals.items():
        p = SC.topk(*fuse(cf, w), spf, fbf)
        B.check_preds(p, users, pool)
        write_sub(p, pool, fn)
        final_preds[fn] = p
    md += [f"Final refits (weeks 11-30 history, 31-42 schedule pool of {len(pool):,}): "
           + ", ".join(f"`{k}` = {v}" for k, v in finals.items()) + f"; all validated; {time.time() - t:.1f}s.\n"]

    # ---- examples (same two users as Phase B/C)
    titles = item_table(("11-20", "21-30", "31-42"))[["tv_show_title", "tv_show_category"]]
    lab = lambda i: (str(titles.loc[i, "tv_show_title"])[:60], str(titles.loc[i, "tv_show_category"])) if i in titles.index else ("?", "?")
    ex = ["### Phase D example users (same users as Phase B/C, main split)\n"]
    for tag, u in (("Heavy viewer", CH["heavy"]), ("Light viewer", CH["light"])):
        truth = sp["main"].target[u]
        ex.append(f"#### {tag}: user {u}; truth = {truth}\n")
        for name in ["Exposure (half-life 4 wk)", "Exposure (no recency)", "Rate-normalised personal", "Hybrid2"] + \
                    (["Hybrid3"] if W3 else []):
            if name not in preds_main:
                continue
            r = preds_main[name][u]
            ex += [f"**{name}** (AP@5 = {apk(truth, r):.3f}):\n",
                   pd.DataFrame([(k + 1, i, *lab(i), "✓" if i in truth else "") for k, i in enumerate(r)],
                                columns=["rank", "tv_show_id", "title", "category", "hit"]).to_markdown(index=False), ""]
        r = final_preds["submission_hybrid2.csv"][u]
        ex += ["**Hybrid2, final weeks 31-42 Top-5:**\n",
               pd.DataFrame([(k + 1, i, *lab(i)) for k, i in enumerate(r)],
                            columns=["rank", "tv_show_id", "title", "category"]).to_markdown(index=False), ""]
    (RES / "phaseD_examples.md").write_text("\n".join(ex) + "\n")
    md.append(f"Total Phase D runtime {time.time() - T0:.1f}s\n")
    (RES / "phaseD.md").write_text("\n".join(md) + "\n")
    json.dump({"best_exp": best_exp, "W2": W2, "W3": W3}, open(RES / "phaseD_choices.json", "w"), indent=1, default=str)
    print("\n".join(md))


if __name__ == "__main__":
    main()
